async function enrichAndWrite() {
  console.log('Fetching Wikipedia metadata for', rawCatalog.length, 'items...');
  const enriched = [];

  for (let i = 0; i < rawCatalog.length; i++) {
    const item = rawCatalog[i];
    const id = `${item.category}-${i + 1}-${item.title.toLowerCase().replace(/[^a-z0-9]/g, '-')}`;
    let image = '';
    let highResImage = '';
    let wikiExtract = '';

    try {
      const res = await fetch(`https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(item.wikiSlug)}`, {
        headers: { 'User-Agent': 'ChronoCultureGame/1.0 (edu@chronoculture.app)' }
      });
      if (res.ok) {
        const data = await res.json();
        image = data.thumbnail?.source || '';
        highResImage = data.originalimage?.source || image;
        wikiExtract = data.extract || '';
      }
    } catch (e) {
      console.warn(`Could not fetch summary for ${item.wikiSlug}:`, e.message);
    }

    enriched.push({
      id,
      category: item.category,
      title: item.title,
      creator: item.creator,
      year: item.year,
      wikiSlug: item.wikiSlug,
      image,
      highResImage,
      genreOrMovement: item.genreOrMovement,
      hint1: item.hint1,
      hint2: item.hint2,
      creatorType: item.creatorType,
      itemType: item.itemType,
      trivia: item.trivia,
      altTitles: item.altTitles,
      altCreators: item.altCreators,
      wikiExtract
    });

    console.log(`[${i + 1}/${rawCatalog.length}] ${item.title} -> ${image ? 'IMG OK' : 'NO IMG'}`);
    await new Promise(r => setTimeout(r, 120));
  }

  const fileContent = `// AUTO-GENERATED CURATED CULTURAL ITEMS FROM WIKIPEDIA
import { CulturalItem } from '../types';

export const CULTURAL_ITEMS: CulturalItem[] = ${JSON.stringify(enriched, null, 2)};
`;

  fs.mkdirSync('./src/data', { recursive: true });
  fs.writeFileSync('./src/data/items.ts', fileContent, 'utf-8');
  console.log('Successfully wrote src/data/items.ts!');
}

enrichAndWrite();
